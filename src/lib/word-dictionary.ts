/**
 * Tra cứu nghĩa tiếng Việt và âm đọc của từ hoặc cụm từ tiếng Nhật N5
 */
export function lookupWord(text: string): WordMeaning | null {
  if (!text) return null;
  // Clean brackets and tildes
  const clean = text.replace(/[\[\]\{\}]/g, "").replace(/^[～~]/, "").trim();
  if (N5_DICTIONARY[clean]) return N5_DICTIONARY[clean];

  // Extract raw kanji if in [kanji]{reading} format
  const kanjiOnly = text.replace(/\[([^\]]+)\]\{[^\}]+\}/g, "$1").replace(/^[～~]/, "").trim();
  if (N5_DICTIONARY[kanjiOnly]) return N5_DICTIONARY[kanjiOnly];

  // Extract kana only
  const kanaOnly = text.replace(/\[[^\]]+\]\{([^\}]+)\}/g, "$1").replace(/^[～~]/, "").trim();
  if (N5_DICTIONARY[kanaOnly]) return N5_DICTIONARY[kanaOnly];

  // Strip trailing particles like は, を, に, で, が, へ, と, も, の, か, よ, ね
  const withoutParticle = clean.replace(/([はをにでへとものかよね])$/, "");
  if (withoutParticle && N5_DICTIONARY[withoutParticle]) {
    return N5_DICTIONARY[withoutParticle];
  }

  // Strip polite endings like ません, ました, ます, ないで, なければ, なくても, て, で
  const root = clean.replace(/(ません|ました|ます|ないで|なければ|なくても|でした)$/, "");
  if (root && N5_DICTIONARY[root]) {
    return N5_DICTIONARY[root];
  }

  return null;
}
